export type CopyKey = keyof typeof EN;

export function t(lang: Lang, key: CopyKey) {
  return (lang === "fil" ? FIL : EN)[key];
}

export function greet(lang: Lang) {
  const h = Number(new Date().toLocaleString("en-US", { hour: "numeric", hour12: false, timeZone: "Asia/Manila" }));
  if (h < 12) return t(lang, "greetMorning");
  if (h < 18) return t(lang, "greetAfternoon");
  return t(lang, "greetEvening");
}

export function statusLine(lang: Lang, call?: "GO" | "CAUTION" | "STAY" | null) {
  if (call === "GO") return t(lang, "statusGo");
  if (call === "CAUTION") return t(lang, "statusCaution");
  if (call === "STAY") return t(lang, "statusStay");
  return t(lang, "readingSea");
}

export function goLine(lang: Lang, call?: "GO" | "CAUTION" | "STAY" | null) {
  if (call === "STAY") return t(lang, "stayLine");
  if (call === "CAUTION") return t(lang, "cautionLine");
  return t(lang, "goLine");
}

export function tideWord(lang: Lang, trend?: string) {
  if (trend === "Rising") return t(lang, "rising");
  if (trend === "Falling") return t(lang, "falling");
  if (trend === "Slack") return t(lang, "slack");
  return trend || "…";
}

export function condWord(lang: Lang, condition: string) {
  const map: Record<string, CopyKey> = {
    "Clear skies": "condClear",
    "Partly cloudy": "condCloud",
    "Mist / fog": "condMist",
    Drizzle: "condDrizzle",
    Rain: "condRain",
    Showers: "condShowers",
    "Heavy rain": "condHeavy",
    Thunderstorm: "condStorm",
    Overcast: "condOvercast",
  };
  const key = map[condition];
  return key ? t(lang, key) : condition;
}

export function windNote(lang: Lang, label: string) {
  const [word, dir] = label.split(" · ");
  const map: Record<string, CopyKey> = {
    "Light breezes": "windLight",
    Moderate: "windMod",
    Fresh: "windFresh",
    Strong: "windStrong",
    "Near gale": "windNearGale",
    "Gale force": "windGale",
  };
  const key = map[word];
  const left = key ? t(lang, key) : word;
  return dir ? `${left} · ${dir}` : left;
}

export function waveNote(lang: Lang, note: string) {
  if (note.startsWith("Safe")) return t(lang, "waveSafe");
  if (note.startsWith("Caution")) return t(lang, "waveCaution");
  if (note.startsWith("Over")) return t(lang, "waveOver");
  return note;
}

export function whatIfTalk(
  lang: Lang,
  waveHt: number,
  catchKg: number,
  netProfit: number,
  breakeven: number,
  otherCost: number,
  money: (n: number) => string,
) {
  if (lang === "fil") {
    if (waveHt > 2) return `Alon ${waveHt.toFixed(1)}m — huwag muna, kahit ${catchKg} kg pa.`;
    if (netProfit > 500) return `Alon ${waveHt.toFixed(1)}m, may ${money(netProfit)} ka after diesel, yelo, at pagkain. Go ka.`;
    if (netProfit > 0) return `Pasok sa break-even (${breakeven} kg), pero ${money(netProfit)} lang natira. Manipis. Ingat.`;
    return `Lugi ${money(netProfit)} ang biyaheng 'to. Huwag muna.`;
  }
  if (waveHt > 2) return `Waves at ${waveHt.toFixed(1)}m beat any catch. I would stay, even at ${catchKg} kg.`;
  if (netProfit > 500) return `Waves are ${waveHt.toFixed(1)}m and this trip clears ${money(netProfit)} after fuel and the ₱${otherCost} ice/food pad. I would go.`;
  if (netProfit > 0) return `You beat break-even (${breakeven} kg), but only ${money(netProfit)} is left. Thin water. Caution.`;
  return `This trip would lose ${money(netProfit)}. Stay for the money.`;
}
